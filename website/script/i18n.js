// Pomocnicza funkcja tłumaczeń dla script.js (np. wyniki skanera)
window.cortexT = (key) => (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    try { localStorage.setItem('cortex_lang', lang); } catch (e) { }

    let decipherIndex = 0;

    // Update texts
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Check for decipher text special case
            if (el.classList.contains('decipher-text')) {
                el.setAttribute('data-text', translations[lang][key]);
                if (window.startDecipherForElement) {
                    setTimeout(() => { window.startDecipherForElement(el); }, decipherIndex * 600);
                    decipherIndex++;
                } else {
                    el.textContent = translations[lang][key];
                }
            } else if (el.tagName === 'TEXTAREA' || el.tagName === 'INPUT') {
                if (el.placeholder) {
                    el.placeholder = translations[lang][key];
                }
            } else if (el.tagName === 'OPTION') {
                el.innerText = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });

    // Update active dropdown entries
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // Update main language button text
    document.querySelectorAll('.lang-btn').forEach(langBtn => {
        langBtn.innerHTML = translations[lang]['lang_name'] + ' <i data-lucide="chevron-down" style="width: 14px; height: 14px;"></i>';
    });
    if (typeof lucide !== 'undefined') lucide.createIcons();

    document.documentElement.lang = lang;
    document.dispatchEvent(new CustomEvent('cortex:langchange', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
    let savedLang = null;
    try { savedLang = localStorage.getItem('cortex_lang'); } catch (e) { }
    if (!savedLang) {
        savedLang = (navigator.language || 'en').startsWith('pl') ? 'pl' : 'en';
    }

    // Menu języka: klik/tap (na telefonach nie ma hovera)
    document.querySelectorAll('.lang-switcher').forEach(switcher => {
        const btn = switcher.querySelector('.lang-btn');
        if (!btn) return;
        btn.addEventListener('click', (e) => {
            e.stopPropagation();
            const open = !switcher.classList.contains('open');
            switcher.classList.toggle('open', open);
            btn.setAttribute('aria-expanded', String(open));
        });
    });

    document.addEventListener('click', () => {
        document.querySelectorAll('.lang-switcher.open').forEach(switcher => {
            switcher.classList.remove('open');
            const btn = switcher.querySelector('.lang-btn');
            if (btn) btn.setAttribute('aria-expanded', 'false');
            if (switcher.contains(document.activeElement)) document.activeElement.blur();
        });
    });

    // Attach click listeners to language options
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const selectedLang = btn.getAttribute('data-lang');
            setLanguage(selectedLang);
        });
    });

    // Initial setting of language
    setLanguage(savedLang);
});
